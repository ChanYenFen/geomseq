"""Benchmark runner -- warms up, reports the minimum of N runs (input generation
untimed), writes JSON + Markdown into benchmarks/results/. See ../README.md.
Usage: python benchmarks/python/run.py [group ...] [--heavy] [--out stem]"""

import argparse
import datetime as _dt
import hashlib
import json
import os
import platform
import sys
import time

_HERE = os.path.dirname(os.path.abspath(__file__))          # benchmarks/python
_BENCH = os.path.dirname(_HERE)                             # benchmarks
_ROOT = os.path.dirname(_BENCH)                             # repo root
sys.path.insert(0, os.path.join(_ROOT, "src"))

import cases as bench_cases  # noqa: E402  (needs the sys.path above)
from geomseq_core import native_bridge  # noqa: E402
from geomseq_core.geometry_utils import sort_points_native  # noqa: E402


# --------------------------------------------------------------------------
# Environment
# --------------------------------------------------------------------------

# Inferred from the platform, not read out of the binary -- a hand-built
# library could differ, so treat it as a label, not proof.
_TOOLCHAIN = {"Windows": "MSVC", "Darwin": "clang++", "Linux": "g++"}


def describe_binary():
    """Identify the native library these numbers actually came from."""
    lib_name = native_bridge._LIB_NAMES[platform.system()]
    path = os.path.join(_ROOT, "src", "geomseq_core", "native", lib_name)
    if not os.path.exists(path):
        return dict(name=lib_name, present=False)

    with open(path, "rb") as fh:
        blob = fh.read()
    return dict(
        name=lib_name,
        present=True,
        size_bytes=len(blob),
        sha256_prefix=hashlib.sha256(blob).hexdigest()[:16],
        mtime=_dt.datetime.fromtimestamp(os.path.getmtime(path)).isoformat(timespec="seconds"),
    )


def describe_env():
    return dict(
        timestamp=_dt.datetime.now().isoformat(timespec="seconds"),
        system=platform.system(),
        release=platform.release(),
        machine=platform.machine(),
        processor=platform.processor() or "unknown",
        toolchain_expected=_TOOLCHAIN.get(platform.system(), "unknown"),
        python=platform.python_version(),
        binary=describe_binary(),
    )


# --------------------------------------------------------------------------
# Measurement
# --------------------------------------------------------------------------

def measure(case, max_reps=5, budget=2.0):
    """Minimum wall time over up to `max_reps` runs, stopping once `budget`
    seconds are spent so a 60-second case is not run five times.
    Returns (best_seconds, reps_done)."""
    best, total, reps = float("inf"), 0.0, 0
    while reps < max_reps:
        payload = case.setup()          # not timed
        t0 = time.perf_counter()
        case.run(payload)
        dt = time.perf_counter() - t0
        best = min(best, dt)
        total += dt
        reps += 1
        if total > budget:
            break
    return best, reps


def warm_up():
    """First call absorbs DLL load + first-call overhead and reads ~10x high."""
    pts = bench_cases.make_points(200)
    sort_points_native(pts, use_two_opt=True)


# --------------------------------------------------------------------------
# Reporting
# --------------------------------------------------------------------------

def fmt_time(seconds):
    if seconds >= 1.0:
        return "%.2f s" % seconds
    if seconds >= 1e-3:
        return "%.1f ms" % (seconds * 1e3)
    return "%.1f us" % (seconds * 1e6)


def markdown_tables(env, records):
    out = []
    out.append("# Baseline -- %s %s / %s"
               % (env["system"], env["machine"], env["toolchain_expected"]))
    out.append("")
    out.append("Generated by `benchmarks/run.py` on %s." % env["timestamp"])
    out.append("")

    binary = env["binary"]
    out.append("| Environment | |")
    out.append("|---|---|")
    out.append("| OS | %s %s (%s) |" % (env["system"], env["release"], env["machine"]))
    out.append("| CPU | %s |" % env["processor"])
    out.append("| Toolchain (expected) | %s |" % env["toolchain_expected"])
    out.append("| Python | %s |" % env["python"])
    if binary.get("present"):
        out.append("| Binary | `%s`, %d bytes, sha256 `%s...`, built %s |"
                   % (binary["name"], binary["size_bytes"],
                      binary["sha256_prefix"], binary["mtime"]))
    else:
        out.append("| Binary | `%s` MISSING |" % binary["name"])
    out.append("")

    for group in bench_cases.GROUPS:
        # Skipped cases are listed after the tables instead, so the absence is
        # visible without leaving a hole in the grid.
        rows = [r for r in records if r["group"] == group and not r.get("skipped")]
        if not rows:
            continue

        # Column set is per-group: each function varies different parameters.
        axis_keys = []
        for r in rows:
            for k in r["axis"]:
                if k not in axis_keys:
                    axis_keys.append(k)

        batched = any(r["batch"] > 1 for r in rows)
        # Observed keys differ per group (out_n here, travel there).
        obs_keys = []
        for r in rows:
            for k in (r.get("observed") or {}):
                if k not in obs_keys:
                    obs_keys.append(k)
        header = (axis_keys + obs_keys + ["best"]
                  + (["per call"] if batched else []) + ["reps"])

        out.append("## `%s`" % group)
        out.append("")
        out.append("| " + " | ".join(header) + " |")
        out.append("|" + "|".join(["---"] * len(header)) + "|")
        for r in rows:
            cells = [str(r["axis"].get(k, "")) for k in axis_keys]
            cells += [str((r.get("observed") or {}).get(k, "")) for k in obs_keys]
            cells.append(fmt_time(r["best_seconds"]))
            if batched:
                cells.append(fmt_time(r["best_seconds"] / r["batch"]))
            cells.append(str(r["reps"]))
            out.append("| " + " | ".join(cells) + " |")
        out.append("")

    skipped = [r for r in records if r.get("skipped")]
    if skipped:
        out.append("Skipped (rerun with `--heavy`): %s"
                   % ", ".join("`%s`" % r["name"] for r in skipped))
        out.append("")
    return "\n".join(out)


# --------------------------------------------------------------------------

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("groups", nargs="*", default=None,
                    help="function names to run (default: all of %s)"
                         % ", ".join(bench_cases.GROUPS))
    ap.add_argument("--heavy", action="store_true",
                    help="include cases that take minutes (large-n 2-opt)")
    ap.add_argument("--reps", type=int, default=5, help="max repetitions per case")
    ap.add_argument("--budget", type=float, default=2.0,
                    help="stop repeating a case once it has burned this many seconds")
    ap.add_argument("--out", default=None,
                    help="output path stem (default: results/baseline-<sys>-<machine>-<date>)")
    args = ap.parse_args(argv)

    wanted = args.groups or bench_cases.GROUPS
    unknown = [g for g in wanted if g not in bench_cases.GROUPS]
    if unknown:
        ap.error("unknown group(s): %s" % ", ".join(unknown))

    env = describe_env()
    if not env["binary"].get("present"):
        print("ERROR: %s not found -- build it first (see README Build)."
              % env["binary"]["name"], file=sys.stderr)
        return 1

    selected = [c for c in bench_cases.all_cases() if c.group in wanted]

    print("warming up...", file=sys.stderr)
    warm_up()

    records = []
    for i, case in enumerate(selected, 1):
        label = "[%d/%d] %s / %s" % (i, len(selected), case.group, case.name)
        if case.heavy and not args.heavy:
            print("%s -- skipped (heavy)" % label, file=sys.stderr)
            records.append(dict(group=case.group, name=case.name, axis=case.axis,
                                batch=case.batch, skipped=True,
                                best_seconds=None, reps=0))
            continue

        print("%s ... " % label, end="", flush=True, file=sys.stderr)
        best, reps = measure(case, max_reps=args.reps, budget=args.budget)

        # Outside the timed region. Never fatal: a broken observer should cost
        # a column, not the whole baseline run.
        observed = None
        if case.observe is not None:
            try:
                observed = case.observe(case.setup())
            except Exception as exc:            # noqa: BLE001
                print("(observe failed: %s) " % exc, end="", file=sys.stderr)

        print("%s (%d reps)" % (fmt_time(best), reps), file=sys.stderr)
        records.append(dict(group=case.group, name=case.name, axis=case.axis,
                            batch=case.batch, skipped=False, observed=observed,
                            best_seconds=best, reps=reps))

    done = [r for r in records if not r.get("skipped")]

    stem = args.out
    if stem is None:
        results_dir = os.path.join(_BENCH, "results")
        os.makedirs(results_dir, exist_ok=True)
        name = "baseline-%s-%s-%s" % (
            env["system"].lower(), env["machine"].lower(),
            _dt.date.today().strftime("%Y%m%d"))
        # A partial run must not silently overwrite the full baseline for the
        # same day -- tag the filename with what was actually measured.
        if args.groups:
            name += "-" + "+".join(args.groups)
        if args.heavy:
            name += "-heavy"
        stem = os.path.join(results_dir, name)

    with open(stem + ".json", "w", encoding="utf-8") as fh:
        json.dump(dict(env=env, heavy=args.heavy, records=records), fh, indent=2)
    md = markdown_tables(env, done + [r for r in records if r.get("skipped")])
    with open(stem + ".md", "w", encoding="utf-8") as fh:
        fh.write(md + "\n")

    print("\nwrote %s.json and %s.md" % (stem, stem), file=sys.stderr)
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
